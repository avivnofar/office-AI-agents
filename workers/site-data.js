/**
 * workers/site-data.js — THE TWO DATA SURFACES OF office.avivnofar.com.
 *
 * Written 2026-08-24 (Session 16, Item B). Pure: **this module imports
 * nothing.** The same rule `owner-channel.js`, `owner-page.js`,
 * `office-policy.js` and `deliverable-lifecycle.js` keep, and for the same
 * reason — plain `node` must be able to load it so
 * `scripts/verify-site-data.js` exercises THE REAL builders rather than a
 * hand-mirror of them. Everything here takes its inputs as arguments; nothing
 * here touches `env`, D1, or the network.
 *
 * ── WHY THIS FILE EXISTS AT ALL ──────────────────────────────────────────
 *
 * `warehouse-office-AI-agents/tasks/office-site/` is a finished four-phase
 * build, 129 checks, and it cannot be deployed. Its `data.js` is generated by
 * a local Node script that shells out to `git log` in two private
 * repositories. **There is no git in a Worker.** A deployed copy would show
 * 2026-08-07 forever — including on the page whose entire purpose is telling
 * the owner what is waiting on him, which is the one thing that must never be
 * stale. So the site's first real dependency was never a page. It was a live
 * data endpoint.
 *
 * ── TWO ENDPOINTS, AND THIS IS A SECURITY BOUNDARY ───────────────────────
 *
 * Not an organisational preference. If both surfaces read one endpoint and
 * only authentication separates them, a single auth bug exposes everything.
 * **The public builder must have no path that can return internal content —
 * not hidden behind a flag, not filtered out at the end: ABSENT.**
 *
 * That is not theoretical in this estate. Eight public files naming real
 * third-party companies, in claims a service-error bug had made unreliable,
 * were removed from the public repo on 2026-08-22. And meeting transcripts —
 * which live one D1 table away from everything the public page wants — carry
 * agent names, internal blockers, task identifiers and sometimes client
 * names.
 *
 * So `buildPublicData()` and `buildAdminData()` share no code path. The
 * public builder never receives a snapshot, never receives a transcript, and
 * cannot be handed one: its signature does not accept them.
 *
 * ── WHITELIST, NEVER BLACKLIST ───────────────────────────────────────────
 *
 * `pick()` below constructs a NEW object out of NAMED KEYS. There is no
 * spread anywhere in the public path, and that absence is the mechanism:
 *
 *   A BLACKLIST FAILS OPEN THE MOMENT SOMEONE ADDS A COLUMN. A WHITELIST
 *   FAILS CLOSED.
 *
 * `scripts/verify-site-data.js` proves it rather than asserting it — it
 * poisons every source object with a field nobody whitelisted and requires
 * that the serialised public response does not contain it. That test fails if
 * a future edit replaces a pick with a spread, which is the only way this
 * property is ever going to be lost.
 *
 * And `pick()` additionally refuses any value that is not a string, a finite
 * number, a boolean or null. A whitelisted key whose value later becomes an
 * object would otherwise carry that object's whole interior through a gate
 * that only ever checked the key's NAME.
 *
 * ── WHERE THE PUBLIC FIELDS COME FROM, AND WHY THAT LINE IS DEFENSIBLE ───
 *
 * Every text field in the public response is either
 *
 *   (a) already published, in this public repo, in
 *       `config/agents-config.json` — the 13 agents' name, role, purpose and
 *       character paragraph; or
 *   (b) written in this file, by hand, to be read by strangers — the
 *       `OFFICE_MECHANISMS` block below.
 *
 * Nothing else. In particular **no D1 text column reaches the public
 * response at any point** — D1 contributes integers and nothing but
 * integers, because `cases.description`, `reports.content` and
 * `meetings.transcript` are exactly the columns that would be catastrophic
 * and are exactly the columns an aggregate query is one careless `SELECT *`
 * away from. `publicCounts()` therefore coerces every value it takes through
 * `Number()` and drops anything that does not survive it.
 *
 * The character bible is NOT a source here. It is a private root document of
 * `back-office-AI-agents` and carries a `private` classification in its own
 * header; the agents' public-facing personas come from the public config
 * instead, which is a narrower and already-published subset of the same
 * material.
 */

/* ─────────────────────────────── The gate ───────────────────────────────── */

/** A value simple enough to cross the public boundary. Anything else — an
 *  object, an array, a function, a NaN — is dropped, because a whitelist that
 *  checks only key names stops being a whitelist the day a value grows an
 *  interior. */
function scalarOrNull(v) {
  if (v === null || v === undefined) return null;
  const t = typeof v;
  if (t === 'string' || t === 'boolean') return v;
  if (t === 'number') return Number.isFinite(v) ? v : null;
  return null;
}

/**
 * Builds a NEW object holding exactly the named keys, and only scalars.
 *
 * **Never `{...src}`.** The construction is the security property: a key the
 * source grows tomorrow cannot appear here, because appearing here requires
 * someone to write its name into a whitelist constant, in this file, in a
 * commit somebody reviews.
 */
function pick(src, keys) {
  const out = {};
  const o = src && typeof src === 'object' ? src : {};
  for (const k of keys) out[k] = scalarOrNull(o[k]);
  return out;
}


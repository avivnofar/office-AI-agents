/* ──────────────────────── /api/admin — the full picture ─────────────────── */

/**
 * THE CONTRACT THIS SHAPE MATCHES, recorded 2026-08-24 by reading
 * `warehouse-office-AI-agents/tasks/office-site/data.js` (read-only) and its
 * generator:
 *
 *   window.OFFICE_SITE_DATA = {
 *     generated_at, generated_by,
 *     agents:        [{ id, slug, name, title, role, purpose, live,
 *                       has_persona, produced[], bible_detail{…} }],
 *     pending_items: [{ id, kind, title, source, detail, status_note }],
 *     activity:      [{ kind, repo, sha, short_sha, date, sort_key, author,
 *                       message }  |  { kind:'session_record', … }],
 *     data_gaps:     [ string ],
 *   }
 *
 * The keys above are reproduced exactly so the existing built site consumes
 * this without being rewritten. **Two of them are honestly empty here and say
 * so in `data_gaps` rather than being quietly dropped:**
 *
 *   bible_detail  the character bible is a private root document of
 *                 back-office-AI-agents. The Worker does not fetch it. The
 *                 built site already has it baked into its own data.js and it
 *                 does not go stale, so serving it live would be work for no
 *                 freshness. `null`, and named as null.
 *   produced      a directory inventory of each agent's campus folder. That
 *                 is a filesystem walk of a private repo; the Worker has no
 *                 filesystem and would need one API call per agent per folder.
 *                 `[]`, and named as empty.
 *
 * The two the site actually needs LIVE — `pending_items` and `activity` — are
 * live, and they are the two that were frozen at 2026-08-07.
 */
export const ADMIN_CONTRACT_KEYS = Object.freeze([
  'generated_at', 'generated_by', 'agents', 'pending_items', 'activity', 'data_gaps',
]);

/** `slug` in the site's contract is `NN-the-name`, matching the campus folder
 *  names. Derived from the config key (`agent-1-perfectionist`) rather than
 *  stored twice — two spellings of one identifier is drift waiting to happen. */
export function agentSlug(agent) {
  const id = Number(agent?.id);
  const key = String(agent?.key || '');
  const m = /^agent-\d+-(.+)$/.exec(key);
  if (!Number.isFinite(id) || !m) return null;
  return `${String(id).padStart(2, '0')}-the-${m[1].replace(/^the-/, '')}`;
}

/**
 * The board, the open questions and the submissions ledger, folded into the
 * site's one `pending_items` shape.
 *
 * WHAT COUNTS AS PENDING, stated rather than implied: a board task the office
 * cannot start (NOT-READY or BLOCKED), a question the office asked the owner
 * that has no answer, and a submission awaiting his decision. A READY task is
 * the office's own work and is not waiting on him; including it would make the
 * list longer and less true.
 */
export function buildPendingItems(snapshot) {
  const items = [];
  const tasks = snapshot?.board?.tasks || [];
  for (const t of tasks) {
    if (t.state !== 'NOT-READY' && t.state !== 'BLOCKED') continue;
    items.push({
      id: `board-${String(t.id || '').toLowerCase()}`,
      kind: t.state === 'BLOCKED' ? 'blocked' : 'decision',
      title: t.title || t.id || null,
      source: `campus/shared/board/BOARD.md, ${t.id}, ${t.state}`,
      detail: t.blockedBy ? `Blocked by: ${t.blockedBy}` : 'No "Blocked by" line — the board does not say what this is waiting on.',
      status_note: t.stage ? `Lifecycle stage: ${t.stage}` : null,
    });
  }

  const questions = snapshot?.questions?.questions || [];
  for (const q of questions) {
    if (!q.open) continue;
    items.push({
      id: `question-${String(q.id || '').toLowerCase()}`,
      kind: 'question',
      title: q.title || q.question || q.id || null,
      source: `channel/to-owner/OPEN-QUESTIONS.md, ${q.id}`,
      detail: q.fallback ? `If no answer comes: ${q.fallback}` : 'No fallback recorded — the office did not say what it will do without an answer.',
      status_note: q.date ? `Asked ${q.date}` : null,
    });
  }

  const submissions = snapshot?.submissions?.submissions || [];
  for (const s of submissions) {
    if (!s.open) continue;
    items.push({
      id: `submission-${String(s.id || '').toLowerCase()}`,
      kind: 'approval',
      title: s.title || s.id || null,
      source: `channel/to-owner/SUBMISSIONS.md, ${s.id}`,
      detail: s.recommend ? `The office recommends: ${s.recommend}` : (s.did || 'No recommendation recorded.'),
      status_note: s.escalation?.rung ? `${s.escalation.rung}${s.escalation.days != null ? ` — ${s.escalation.days} days open` : ''}` : null,
    });
  }

  return items;
}

/**
 * Recent office activity from D1 — reports written and meetings held.
 *
 * **NO TRANSCRIPTS AND NO REPORT BODIES.** The caller selects titles and
 * timestamps; this maps them. `meetings.transcript` and `reports.content` are
 * the two columns this estate most needs never to leak, and the way they do
 * not leak is that nothing selects them.
 *
 * NOT INCLUDED, and named in `data_gaps` rather than silently absent: the git
 * commit feed. `data.js` built it by shelling out to `git log` in two private
 * repos, which is precisely what a Worker cannot do and precisely why that
 * file froze. Reproducing it would mean paginating two GitHub Contents APIs on
 * every page load. It is a real gap; it is not a pretended one.
 */
export function buildActivity({ reports = [], meetings = [] } = {}) {
  const out = [];
  for (const r of reports) {
    out.push({
      kind: 'report',
      repo: null,
      date: r.created_at || null,
      sort_key: r.created_at || '',
      agent_id: Number.isFinite(Number(r.agent_id)) ? Number(r.agent_id) : null,
      type: r.type || null,
      severity: r.severity || null,
      message: r.title || null,
    });
  }
  for (const m of meetings) {
    out.push({
      kind: 'meeting',
      repo: null,
      date: m.created_at || null,
      sort_key: m.created_at || '',
      agent_id: null,
      type: m.type || null,
      severity: null,
      message: `${m.type || 'meeting'} — ${m.attendee_count ?? '?'} attending`,
    });
  }
  return out.sort((a, b) => String(b.sort_key).localeCompare(String(a.sort_key)));
}

/**
 * THE ADMIN RESPONSE. Authenticated. Full data.
 *
 * `errors` is carried through rather than swallowed, and that is the same
 * judgement `buildOwnerState()` made for the same reason: a surface that
 * silently omitted the office's own read errors would be the most misleading
 * one in the system — the owner would read an empty pending list as "nothing
 * is waiting on me" when the truth was "the office could not read its board".
 */
export function buildAdminData({
  agents = [], counts = {}, snapshot = null,
  reports = [], meetings = [], generatedAt = null, versionId = null,
} = {}) {
  const list = Array.isArray(agents) ? agents : [];
  const snapshotReadable = !!(snapshot && (snapshot.board || snapshot.requirements));

  return {
    ok: true,
    surface: 'admin',
    generated_at: typeof generatedAt === 'string' ? generatedAt : null,
    generated_by: `site-data.js (live, Worker version ${versionId || 'unknown'})`,
    agents: list.map((a) => ({
      id: Number(a.id),
      slug: agentSlug(a),
      name: a.name || null,
      title: `AGENT ${a.id} — ${String(a.name || '').toUpperCase()}`,
      role: a.role || null,
      purpose: a.purpose || null,
      character: a.character || null,
      tier: a.tier || null,
      clearance: a.clearance || null,
      status: a.status || null,
      live: a.status === 'active',
      has_persona: !!a.character,
      // Named, not omitted — see ADMIN_CONTRACT_KEYS' note.
      produced: [],
      bible_detail: null,
    })),
    counts: publicCounts(counts),
    pending_items: buildPendingItems(snapshot),
    activity: buildActivity({ reports, meetings }),
    // The office's own errors reading its own files. Reported, never hidden.
    errors: Array.isArray(snapshot?.errors) ? snapshot.errors : [],
    data_gaps: [
      snapshotReadable
        ? 'pending_items is live: the board, the open questions and the submissions ledger, read from back-office at request time.'
        : 'THE OFFICE COULD NOT READ ITS OWN BOARD. pending_items is empty because the read failed, NOT because nothing is pending — see `errors`.',
      'bible_detail is null. The character bible is a private root document and the Worker does not fetch it; the built site carries its own copy, which does not go stale.',
      'produced is empty. It is a directory inventory of each agent\'s campus folder — a filesystem walk of a private repo, which a Worker has no filesystem to perform.',
      'activity carries reports and meetings from the office\'s database, with NO report bodies and NO meeting transcripts — those columns are never selected.',
      'activity does NOT carry the git commit feed. data.js built that by shelling out to `git log` in two private repos, which is exactly what a Worker cannot do and exactly why that file froze on 2026-08-07.',
      'Counts are totals since the simulation began on 2026-06-17, not per-day figures.',
    ],
  };
}

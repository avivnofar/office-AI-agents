#!/usr/bin/env node
/**
 * scripts/verify-designer-gallery.js — does the Designer's own gallery stay
 * honest, and are the request-form's write-side refusals real?
 *
 * Written 2026-08-31 ("office console: the designer page" session).
 * Run: node scripts/verify-designer-gallery.js
 *
 * ── WHAT THIS PROVES ────────────────────────────────────────────────────
 *
 * 1. `parseProvenanceNote()` round-trips the exact shape
 *    `renderAssetProvenance()` writes — including the "Polished FROM" text
 *    a polish note carries, since that is the DATA the pairing runs on.
 * 2. A folder with no image files is an empty gallery, not an error. A
 *    missing or malformed provenance note is a reported PROBLEM, never a
 *    silent drop.
 * 3. Pairing a draft to its polish uses the note's own recorded
 *    relationship, not a filename guess — a slug ending in the literal word
 *    "polished" must not break it.
 * 4. A polish asset whose declared draft is missing from the listing is
 *    still shown (not dropped) and is flagged as a problem.
 * 5. Every new route is registered in admin-gate.js's alias map by hand,
 *    sits under /api/admin (the shared prefix gate), and the handlers hold
 *    no authentication check of their own.
 * 6. `/api/admin/designer/generate` refuses a polish request with no
 *    `sourceAssetPath` before any provider is called, and never lets a
 *    caller-supplied path escape the Designer's own folder.
 *
 * NO NETWORK for §1-4: `designer-assets.js` imports nothing, and
 * `globalThis.fetch` is a tripwire. §5-6 read `agent-runner.js`'s and
 * `admin-gate.js`'s SOURCE TEXT rather than executing the Worker, the same
 * shape `verify-artifact-gallery.js` §4 uses for the same reason (the
 * runner needs live D1/KV/env bindings this script does not have).
 */

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import {
  DESIGNER_ASSET_DIR, provenancePathFor, isDesignerAssetImage,
  parseProvenanceNote, buildDesignerGallery,
} from '../workers/designer-assets.js';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..');

globalThis.fetch = () => { throw new Error('verify-designer-gallery.js: a network call was attempted — designer-assets.js must make none'); };

let pass = 0;
const fails = [];
function check(name, cond, detail = '') {
  if (cond) { pass += 1; return; }
  fails.push(`${name}${detail ? ` — ${detail}` : ''}`);
}
function section(title) { console.log(`\n${title}`); }

/* ═══════════ §1 the parser is renderAssetProvenance()'s inverse ═════════ */

section('§1 the provenance note round-trips, including the polish relationship');

const DRAFT_NOTE = [
  '# Provenance — campus/agents/09-the-designer/assets/2026-08-31-test-mark.jpg',
  '',
  '- **Asset:** `campus/agents/09-the-designer/assets/2026-08-31-test-mark.jpg`',
  '- **Generated by:** Agent 9 — The Designer',
  '- **Model:** `@cf/black-forest-labs/flux-1-schnell` (provider `cloudflare-images`, image lane role `draft`)',
  '- **Date:** 2026-08-31',
  '- **Prompt:** A test emblem, for the verifier only',
  '- **Size:** 12345 bytes',
  '',
  '*Required by `AGENTS-CHARACTER-CORE-v2.md` AGENT 9...*',
].join('\n');

const POLISH_NOTE = [
  '# Provenance — campus/agents/09-the-designer/assets/2026-08-31-test-mark-polished.jpg',
  '',
  '- **Asset:** `campus/agents/09-the-designer/assets/2026-08-31-test-mark-polished.jpg`',
  '- **Generated by:** Agent 9 — The Designer',
  '- **Model:** `gemini-3-pro-image-preview` (provider `gemini-images`, image lane role `polish`)',
  '- **Date:** 2026-08-31',
  '- **Prompt:** [polish instruction] flatten the tones',
  '- **Size:** 22222 bytes',
  '- **Note:** Polished FROM `campus/agents/09-the-designer/assets/2026-08-31-test-mark.jpg` (12345 bytes, @cf/black-forest-labs/flux-1-schnell). The draft\'s own bytes were sent as the input image.',
  '',
  '*Required by...*',
].join('\n');

const draftParsed = parseProvenanceNote(DRAFT_NOTE);
check('a draft note parses', draftParsed.ok === true);
check('asset path is read', draftParsed.assetPath === 'campus/agents/09-the-designer/assets/2026-08-31-test-mark.jpg');
check('model/provider/role all parse out of one line', draftParsed.model === '@cf/black-forest-labs/flux-1-schnell' && draftParsed.provider === 'cloudflare-images' && draftParsed.role === 'draft');
check('bytes parses as a number', draftParsed.bytes === 12345);
check('a draft note carries no polishedFrom', draftParsed.polishedFrom === null);

const polishParsed = parseProvenanceNote(POLISH_NOTE);
check('a polish note parses', polishParsed.ok === true);
check('polishedFrom is read FROM THE NOTE TEXT, not guessed from a filename',
  polishParsed.polishedFrom === 'campus/agents/09-the-designer/assets/2026-08-31-test-mark.jpg');

const MALFORMED = ['', '   ', 'not a provenance note at all', '- **Model:** `x` (provider `y`, image lane role `z`)'];
check('every malformed note is refused with a reason',
  MALFORMED.every((t) => { const r = parseProvenanceNote(t); return r.ok === false && typeof r.reason === 'string' && r.reason.length > 5; }));

check('provenancePathFor() strips the extension and appends the fixed suffix',
  provenancePathFor('2026-08-31-x.jpg') === '2026-08-31-x.provenance.md');
check('isDesignerAssetImage rejects a provenance file itself',
  isDesignerAssetImage('2026-08-31-x.jpg') === true && isDesignerAssetImage('2026-08-31-x.provenance.md') === false);

/* ═══════════ §2 empty folder is empty; a broken note is a problem ═══════ */

section('§2 an empty folder is not an error; a missing or broken note is a reported problem');

const empty = buildDesignerGallery([], {});
check('no entries -> no assets, no problems', empty.assets.length === 0 && empty.problems.length === 0);

const DIR_ONE_MISSING = [{ name: '2026-08-31-x.jpg', type: 'file', size: 100 }];
const missingNote = buildDesignerGallery(DIR_ONE_MISSING, {});
check('an image with no readable provenance is a PROBLEM, not silently dropped from the count',
  missingNote.assets.length === 0 && missingNote.problems.length === 1 && /2026-08-31-x\.provenance\.md/.test(missingNote.problems[0].reason));

const DIR_ONE_BROKEN = [{ name: '2026-08-31-x.jpg', type: 'file', size: 100 }];
const brokenNote = buildDesignerGallery(DIR_ONE_BROKEN, { '2026-08-31-x.jpg': { text: 'not a provenance note', reason: null } });
check('a note that fails to parse is a problem too',
  brokenNote.assets.length === 0 && brokenNote.problems.length === 1);

/* ═══════════ §3 pairing runs on the note's own data, not a filename guess ═ */

section('§3 a draft and its polish pair on the recorded relationship, not on filenames');

const PAIR_DIR = [
  { name: '2026-08-31-test-mark.jpg', type: 'file', size: 12345 },
  { name: '2026-08-31-test-mark-polished.jpg', type: 'file', size: 22222 },
];
const PAIR_PROV = {
  '2026-08-31-test-mark.jpg': { text: DRAFT_NOTE, reason: null },
  '2026-08-31-test-mark-polished.jpg': { text: POLISH_NOTE, reason: null },
};
const paired = buildDesignerGallery(PAIR_DIR, PAIR_PROV);
check('exactly one draft is returned (the polish is attached, not listed separately)', paired.assets.length === 1);
check('the draft carries its polish', !!paired.assets[0].polished && paired.assets[0].polished.name === '2026-08-31-test-mark-polished.jpg');
check('no problems for a correctly-paired set', paired.problems.length === 0);

// A slug that itself ends in the word "polished" must not confuse a
// filename-based pairing — this module's pairing does not use filenames at
// all, so this is a direct test of that claim.
const TRICKY_DRAFT_NOTE = DRAFT_NOTE
  .replace('2026-08-31-test-mark.jpg', '2026-08-31-already-polished.jpg');
const TRICKY_DIR = [{ name: '2026-08-31-already-polished.jpg', type: 'file', size: 12345 }];
const tricky = buildDesignerGallery(TRICKY_DIR, { '2026-08-31-already-polished.jpg': { text: TRICKY_DRAFT_NOTE, reason: null } });
check('a slug ending in "polished" is still read as an ordinary draft with no polish attached',
  tricky.assets.length === 1 && tricky.assets[0].polished === null && tricky.problems.length === 0);

/* ═══════════ §4 an orphaned polish is shown, and flagged ═══════════════ */

section('§4 a polish whose declared draft is missing is still shown, and flagged');

const ORPHAN_DIR = [{ name: '2026-08-31-test-mark-polished.jpg', type: 'file', size: 22222 }];
const orphan = buildDesignerGallery(ORPHAN_DIR, { '2026-08-31-test-mark-polished.jpg': { text: POLISH_NOTE, reason: null } });
check('the orphaned polish is still returned as an asset (not silently dropped)',
  orphan.assets.length === 1 && orphan.assets[0].role === 'polish');
check('and it is flagged as a problem, naming the missing draft',
  orphan.problems.length === 1 && /test-mark\.jpg/.test(orphan.problems[0].reason));

/* ═══════════ §5 the routes: registered, gated, mapped by hand ═══════════ */

section('§5 the routes exist, are inside the Access path, and are gated');

const GATE = readFileSync(join(repo, 'workers', 'admin-gate.js'), 'utf8');
const RUNNER = readFileSync(join(repo, 'workers', 'agent-runner.js'), 'utf8');

check('the alias map carries explicit entries for all three routes',
  /\['designer\/gallery', '\/api\/admin\/designer\/gallery'\]/.test(GATE)
  && /\['designer\/asset', '\/api\/admin\/designer\/asset'\]/.test(GATE)
  && /\['designer\/generate', '\/api\/admin\/designer\/generate'\]/.test(GATE));

check('the generate route is a POST under /api/admin, covered by the shared prefix gate',
  /request\.method === 'POST' && url\.pathname === '\/api\/admin\/designer\/generate'/.test(RUNNER)
  && /const AUTHENTICATED_PREFIXES\s*=\s*\['\/api\/agents\/', '\/api\/admin'\]/.test(RUNNER));
check('the gallery and asset reads are GET under /api/admin too',
  /request\.method === 'GET' && url\.pathname === '\/api\/admin\/designer\/gallery'/.test(RUNNER)
  && /request\.method === 'GET' && url\.pathname === '\/api\/admin\/designer\/asset'/.test(RUNNER));

check('the generate handler contains no authentication check of its own', (() => {
  const i = RUNNER.indexOf("url.pathname === '/api/admin/designer/generate'");
  if (i < 0) return false;
  const end = RUNNER.indexOf("-- /api/admin — THE FULL PICTURE", i);
  const body = RUNNER.slice(i, end > i ? end : i + 6000);
  return !/ADMIN_TOKEN|adminCredential|adminCookieValue/.test(body);
})(), 'a handler-local check is the one a refactor moves');

check('the /admin/designer page is under the /admin prefix (the second, page-level gate)',
  /url\.pathname === '\/admin\/designer' \|\| url\.pathname === '\/admin\/designer\/'/.test(RUNNER));

/* ═══════════ §6 polish requires a source, and the path never escapes ═══ */

section('§6 a polish with no source is a 400, and a source path can never leave the folder');

const genIdx = RUNNER.indexOf("url.pathname === '/api/admin/designer/generate'");
const genEnd = RUNNER.indexOf("-- /api/admin — THE FULL PICTURE", genIdx);
const GEN_BODY = RUNNER.slice(genIdx, genEnd > genIdx ? genEnd : genIdx + 6000);

check('an empty/missing sourceAssetPath on a polish request is refused with its own error code',
  /polish_requires_source/.test(GEN_BODY) && /400, origin/.test(GEN_BODY));
check('the refusal happens BEFORE any provider is called — the source check precedes runDesignerAsset()',
  GEN_BODY.indexOf('polish_requires_source') < GEN_BODY.indexOf('runDesignerAsset(env'));
check('a source path is checked against the Designer\'s own directory and against ".." before any fetch',
  /sourceAssetPath\.startsWith\(`\$\{DESIGNER_ASSET_DIR\}\/`\)/.test(GEN_BODY) && /sourceAssetPath\.includes\('\.\.'\)/.test(GEN_BODY));
check('a polish never silently downgrades to a draft — no path in this handler switches role away from what the caller asked',
  !/role\s*=\s*'draft'\s*;[^;]*role === 'polish'/.test(GEN_BODY), // no reassignment-then-recheck pattern
  'the role is read once into a const and never reassigned');
check('the commit-failed and readback-failed outcomes are distinct error codes, not folded into one',
  /commit_failed/.test(GEN_BODY) && /readback_failed/.test(GEN_BODY) && /quota_exhausted/.test(GEN_BODY) && /model_unavailable/.test(GEN_BODY));

/* ══════════════════════════════ Result ══════════════════════════════════ */

console.log(`\ndesigner-gallery: ${pass} checks passed, ${fails.length} failed`);
if (fails.length) {
  console.log('\nFAILED:');
  for (const f of fails) console.log(`  ✗ ${f}`);
  process.exit(1);
}
console.log(`  the provenance note is the manifest; pairing is data, not a filename guess. (${DESIGNER_ASSET_DIR})\n`);
process.exit(0);
